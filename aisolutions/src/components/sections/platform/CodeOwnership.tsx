import { useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { Eye, PencilLine, Download, FileCode2, Folder } from "lucide-react";
import { TiltCard, Reveal, BorderBeam } from "@/components/fx";
import { SectionHeading } from "@/components/ui/Section";
import { cn } from "@/lib/cn";

const MODES = [
  { key: "inspect", label: "Inspect", icon: Eye, body: "Browse every generated file, with the agent that wrote it and why." },
  { key: "edit", label: "Edit", icon: PencilLine, body: "Change code directly or ask the AI to change it. Your edits are kept on regeneration." },
  { key: "export", label: "Export", icon: Download, body: "Download the full repository or push it to your own Git provider. No lock-in." },
] as const;

const FILES = ["app/", "  routes/candidates.ts", "  agents/screening.py", "  db/schema.sql", "  web/pages/Dashboard.tsx", "tests/", "Dockerfile"];

const SNIPPETS: Record<(typeof MODES)[number]["key"], string[]> = {
  inspect: ["// generated by Backend Agent", "export async function rankCandidates(jobId: string) {", "  const job = await db.jobs.find(jobId);", "  const matches = await vector.search(job.embedding, 50);", "  return scoreAndSort(matches, job.requirements);", "}"],
  edit: ["export async function rankCandidates(jobId: string) {", "  const job = await db.jobs.find(jobId);", "- const matches = await vector.search(job.embedding, 50);", "+ const matches = await vector.search(job.embedding, 100);", "+ // edited by you: wider shortlist", "  return scoreAndSort(matches, job.requirements);"],
  export: ["$ infodrizzle export recruitment-app", "  packaging 148 files", "  writing README and .env.example", "  bundling tests and Dockerfile", "✓ recruitment-app.zip ready", "✓ pushed to git remote: origin/main"],
};

export function CodeOwnership() {
  const [mode, setMode] = useState<(typeof MODES)[number]["key"]>("inspect");

  return (
    <section className="relative py-20 sm:py-28">
      <div aria-hidden className="absolute left-1/2 top-1/2 h-[500px] w-[80%] -translate-x-1/2 -translate-y-1/2 rounded-full bg-violet/10 blur-[140px]" />
      <div className="container relative grid items-center gap-12 lg:grid-cols-2">
        <div>
          <SectionHeading align="left" eyebrow="Code ownership" title="You own every line it writes." subtitle="Generated code is real, readable source code. Inspect it, change it and take it with you." className="mb-8" />
          <div className="space-y-3">
            {MODES.map((m) => (
              <button
                key={m.key}
                type="button"
                onClick={() => setMode(m.key)}
                onMouseEnter={() => setMode(m.key)}
                className={cn("relative flex w-full items-start gap-4 rounded-2xl border p-4 text-left transition-colors", mode === m.key ? "border-violet/40" : "border-transparent hover:border-line")}
              >
                {mode === m.key && <motion.span layoutId="own-active" className="absolute inset-0 rounded-2xl bg-violet/10" transition={{ type: "spring", stiffness: 380, damping: 32 }} />}
                <span className={cn("relative flex h-10 w-10 shrink-0 items-center justify-center rounded-xl border transition-colors", mode === m.key ? "border-cyan/50 text-cyan" : "border-line text-ink-muted")}>
                  <m.icon className="h-5 w-5" />
                </span>
                <span className="relative">
                  <span className="block font-display text-lg font-medium">{m.label}</span>
                  <span className="mt-1 block text-sm text-ink-muted">{m.body}</span>
                </span>
              </button>
            ))}
          </div>
        </div>
        <Reveal>
          <TiltCard max={6} className="rounded-2xl">
            <div className="relative overflow-hidden rounded-2xl border border-line bg-[#0B0E18] shadow-panel">
              <BorderBeam duration={9} />
              <div className="flex items-center gap-2 border-b border-line px-4 py-3">
                <span className="h-3 w-3 rounded-full bg-danger/70" />
                <span className="h-3 w-3 rounded-full bg-warning/70" />
                <span className="h-3 w-3 rounded-full bg-success/70" />
                <span className="ml-3 truncate font-mono text-xs text-ink-faint">recruitment-app / {mode}</span>
              </div>
              <div className="grid min-h-[280px] grid-cols-[auto_1fr]">
                <ul className="hidden border-r border-line p-3 font-mono text-[11px] text-ink-faint sm:block">
                  {FILES.map((f) => (
                    <li key={f} className="flex items-center gap-1.5 whitespace-pre py-0.5">
                      {f.endsWith("/") ? <Folder className="h-3 w-3 text-violet-soft" /> : <FileCode2 className="h-3 w-3 text-cyan/70" />}
                      {f}
                    </li>
                  ))}
                </ul>
                <div className="min-w-0 overflow-hidden p-4 font-mono text-[11.5px] leading-6 sm:text-xs">
                  <AnimatePresence mode="wait">
                    <motion.div key={mode} initial="hidden" animate="show" exit={{ opacity: 0, x: -10 }} variants={{ hidden: {}, show: { transition: { staggerChildren: 0.07 } } }}>
                      {SNIPPETS[mode].map((line, i) => (
                        <motion.div
                          key={i}
                          variants={{ hidden: { opacity: 0, x: 12 }, show: { opacity: 1, x: 0 } }}
                          className={cn(
                            "truncate whitespace-pre",
                            line.startsWith("+") && "bg-success/10 text-success",
                            line.startsWith("-") && "bg-danger/10 text-danger line-through decoration-danger/40",
                            line.startsWith("//") && "text-ink-faint",
                            line.startsWith("✓") && "text-success",
                            line.startsWith("$") && "text-cyan",
                          )}
                        >
                          <span className="mr-3 select-none text-ink-faint/50">{String(i + 1).padStart(2, " ")}</span>
                          {line}
                        </motion.div>
                      ))}
                    </motion.div>
                  </AnimatePresence>
                </div>
              </div>
            </div>
          </TiltCard>
        </Reveal>
      </div>
    </section>
  );
}
